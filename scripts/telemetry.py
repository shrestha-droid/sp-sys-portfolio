#!/usr/bin/env python3
"""Regenerate telemetry.js from the real git history of each project's local repository.

Counts every commit (all branches), lines of source code tracked by git, test cases, and a
per-day commit histogram. Run from the portfolio root:  python3 scripts/telemetry.py
Paths are this machine's checkouts; a missing repo is skipped, not guessed.
"""
import collections, datetime, json, os, re, subprocess

HOME = os.path.expanduser('~')
REPOS = {  # project id in projects.js -> local checkout
    'conclave': 'Documents/Codex/2026-10-24/how-x20/outputs/ai-council-cli',
    'branch-hq': 'branch-hq', 'vault-v2': 'Downloads/zero-trust-vault', 'spherex': 'nasa-space-apps-2026/planet-x-spherex',
    'clps': 'nasa-space-apps-2026/clps-lunar-mission-browser', 'drishti': 'drishti', 'bheed-drishti': 'Bheed-Drishti',
    'ring0': 'ring0', 'kakeya-records': 'kakeya-records', 'mend': 'mend', 'ncii-shield': 'ncii-shield', 'friday': 'Friday_Project', 'vault-v1': 'client vault',
}
LANG = {  # extension -> (language, GitHub linguist colour)
    '.ts': ('TypeScript', '#3178c6'), '.tsx': ('TypeScript', '#3178c6'), '.js': ('JavaScript', '#f1e05a'), '.mjs': ('JavaScript', '#f1e05a'),
    '.py': ('Python', '#3572A5'), '.cpp': ('C++', '#f34b7d'), '.hpp': ('C++', '#f34b7d'), '.h': ('C++', '#f34b7d'), '.cc': ('C++', '#f34b7d'),
    '.html': ('HTML', '#e34c26'), '.css': ('CSS', '#663399'), '.sql': ('SQL', '#e38c00'), '.sh': ('Shell', '#89e051'),
}
SKIP = re.compile(r'(^|/)(node_modules|dist|dist-single|out|build|vendor|\.next|__pycache__|friday_env|test-results)/|\.min\.|package-lock|\.d\.ts$')
TEST_FILE, TEST_CASE = re.compile(r'(\.test\.|\.spec\.|(^|/)tests?/|(^|/)test_)'), re.compile(r'^\s*(it|test)\s*\(|^\s*def test_', re.M)

def git(repo, *args):
    return subprocess.run(['git', '-C', repo, *args], capture_output=True, text=True).stdout

projects, days, langs = {}, collections.Counter(), collections.Counter()
for pid, rel in REPOS.items():
    repo = os.path.join(HOME, rel)
    if not os.path.isdir(os.path.join(repo, '.git')):
        continue
    dates = git(repo, 'log', '--all', '--format=%ad', '--date=short').split()
    loc = tests = 0
    for f in git(repo, 'ls-files').splitlines():
        ext = os.path.splitext(f)[1]
        if ext not in LANG or SKIP.search(f):
            continue
        try:
            text = open(os.path.join(repo, f), encoding='utf-8', errors='ignore').read()
        except OSError:
            continue
        n = sum(1 for line in text.splitlines() if line.strip())
        loc += n; langs[LANG[ext]] += n
        if TEST_FILE.search(f):
            tests += len(TEST_CASE.findall(text))
    days.update(dates)
    projects[pid] = {'commits': len(dates), 'loc': loc, 'tests': tests, 'first': min(dates), 'last': max(dates)}

out = {
    'generated': datetime.date.today().isoformat(),
    'totals': {'commits': sum(p['commits'] for p in projects.values()), 'loc': sum(p['loc'] for p in projects.values()),
               'tests': sum(p['tests'] for p in projects.values()), 'projects': len(projects),
               'activeDays': len(days), 'peakDay': max(days.values()) if days else 0},
    'projects': projects,
    'days': dict(sorted(days.items())),
    'langs': [[name, n, col] for (name, col), n in langs.most_common()],
}
with open('telemetry.js', 'w') as fh:
    fh.write('// Generated by scripts/telemetry.py from local git history. Do not edit by hand.\n')
    fh.write('const TELEMETRY = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(json.dumps(out['totals']), {k: (v['commits'], v['loc'], v['tests']) for k, v in projects.items()})
